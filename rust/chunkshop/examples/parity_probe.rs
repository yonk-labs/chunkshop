//! SC-12 bit-level parity probe: does the Rust port produce the same vectors as
//! Python for the models chunkshop actually ships?
//!
//! Goes through chunkshop's OWN embedder (`FastembedEmbedder`), not raw
//! fastembed — the int8 default is resolved by `user_defined_source`, so a probe
//! using `EmbeddingModel::` directly would pass while testing nothing real.
//!
//! This is a MANUAL probe: it prints `dim` / `|v|` / `first8` / `sum` for eyeball
//! comparison against the same figures printed by the Python side. The automated
//! gate is `tests/clip_embedding_parity.rs`, which compares FULL binary reference
//! vectors (`tests/parity-fixtures/clip_{text,vision}_full_reference.bin`,
//! generated by `tests/parity/generate_clip_full_vectors.py`) per component.
//! A prior JSON summary reference (`tests/parity/embedding-reference.json`) was
//! retired: `first8`/`sum`/`l2_norm` cannot express a per-component tolerance.
use chunkshop::config::FastembedEmbedderConfig;
use chunkshop::embedder::FastembedEmbedder;
use fastembed::{
    EmbeddingModel, ImageEmbedding, ImageEmbeddingModel, ImageInitOptions, InitOptions,
    TextEmbedding,
};

const FIXTURE: &str = "a game sprite or pixel art";

fn report(label: &str, v: &[f32]) {
    let norm: f32 = v.iter().map(|x| x * x).sum::<f32>().sqrt();
    let first8: Vec<f32> = v[..8.min(v.len())]
        .iter()
        .map(|x| (x * 1e8).round() / 1e8)
        .collect();
    println!("{label:<16} dim={:<4} |v|={norm:.6}", v.len());
    println!("{:<16} first8 = {first8:?}", "");
    println!("{:<16} sum    = {:.8}", "", v.iter().sum::<f32>());
    if std::env::var("PARITY_FULL").is_ok() {
        println!(
            "{label}_FULL {}",
            v.iter()
                .map(|x| format!("{x:.10}"))
                .collect::<Vec<_>>()
                .join(",")
        );
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    // 1. CLIP text tower — stock registry variant. Already verified ~1e-7.
    let opts = InitOptions::new(EmbeddingModel::ClipVitB32).with_show_download_progress(false);
    let mut clip = TextEmbedding::try_new(opts)?;
    report("clip_text", &clip.embed(vec![FIXTURE], None)?[0]);

    // 2. chunkshop's DEFAULT text embedder, through chunkshop's own resolution.
    //    `Xenova/bge-base-en-v1.5-int8` is not a stock fastembed variant; it is
    //    routed by `user_defined_source` to the quantized ONNX with CLS pooling.
    let cfg = FastembedEmbedderConfig {
        model_name: "Xenova/bge-base-en-v1.5-int8".to_string(),
        dim: 768,
        batch_size: 32,
        threads: Some(4),
        hf_repo: None,
        onnx_path: None,
        pooling: "cls".to_string(),
        additional_files: Default::default(),
    };
    let mut bge = FastembedEmbedder::new(cfg)?;
    report("text_bge_int8", &bge.embed(vec![FIXTURE.to_string()])?[0]);

    // 3. CLIP vision tower against the committed fixture image.
    let img = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../docs/samples/images/sprite_knight.png"
    );
    let iopts =
        ImageInitOptions::new(ImageEmbeddingModel::ClipVitB32).with_show_download_progress(false);
    let mut vision = ImageEmbedding::try_new(iopts)?;
    report("clip_vision", &vision.embed(vec![img], None)?[0]);
    Ok(())
}
