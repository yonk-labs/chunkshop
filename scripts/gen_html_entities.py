#!/usr/bin/env python3
"""Generate rust/chunkshop-parsers/src/html_entities.rs from bs4's own entity table, so the Rust
HTML parser decodes exactly the names Python's HTMLParser path does. Run with python/.venv."""
from pathlib import Path
from bs4.dammit import EntitySubstitution as E
import bs4

rows = sorted(E.HTML_ENTITY_TO_CHARACTER.items())
out = Path(__file__).resolve().parent.parent / "rust/chunkshop-parsers/src/html_entities.rs"
lit = lambda s: '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'
body = "".join(f"    ({lit(k)}, {lit(v)}),\n" for k, v in rows)
out.write_text(
    f"//! GENERATED by scripts/gen_html_entities.py from beautifulsoup4 {bs4.__version__}; do not edit.\n"
    f"/// Sorted by name (names have no trailing `;`).\n"
    f"pub(crate) static ENTITIES: &[(&str, &str)] = &[\n{body}];\n"
)
print(len(rows), "entities ->", out)
